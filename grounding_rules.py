"""AIの生成物に必ず適用する、根拠・出典のルール(全AI機能のプロンプトに強制する共通指示)。

論文・レポートの下書きでは、存在しない判例・文献・条文番号を、もっともらしく書いてしまう
ことが最も危険な誤りになる。そこで、機能の種類ごとに次の3つの形で同じルールを付ける。

- GROUNDING_RULES_DOCUMENT : 文章(本文・ノート・課題)を返す機能。5つのルールすべて。
- GROUNDING_RULES_STRUCTURED: JSONを返す機能(構成案など)。出力の形式を壊さないよう、
  JSONの文字列の値の中だけでルールを守らせ、末尾の追加文章は求めない。
- GROUNDING_RULES_CHAT      : 対話機能。資料の提示がない場合でも守るべき部分だけ。

出力の言語は各機能の言語指定(language_instruction等)に従うため、ここでは日本語で書く。
"""

VERIFY_MARK = "【要検証】"
CHECK_MARK = "要確認"

GROUNDING_RULES_DOCUMENT = f"""

## 根拠と出典のルール(必ず守る)
1. 主張の根拠は、ユーザーが提示した資料(貼り付けられた本文、添付ファイルの抜粋、参考文献の一覧)にあるものだけを使う。
2. 資料にない判例・文献・条文番号・統計・人名は、絶対に挙げない。必要だと思う場合は、具体名を書かず「{CHECK_MARK}」とだけ書く。
3. 各主張には、根拠となる資料名と該当箇所を括弧で付ける。資料が提示されていない場合は、一般的な説明にとどめ、断定せず、具体的な出典を創作しない。
4. 確信が持てない箇所や、論理が飛んでいる箇所は、その文末に「{VERIFY_MARK}」と付ける。
5. 最後に、本文とは見出しを分けて、反対説や、論旨の弱点になりそうな点を3つ挙げる(提出する文書には含めない、検討用の補足と分かる見出しにする)。"""

GROUNDING_RULES_STRUCTURED = f"""

## 根拠と出典のルール(必ず守る。出力はJSONのままにする)
- 根拠にしてよいのは、ユーザーが提示した資料にあるものだけ。資料にない判例・文献・条文番号・統計・人名は、JSONのどの値にも書かない。必要なら「{CHECK_MARK}」とだけ書く。
- 確信が持てない記述は、その文字列の値の末尾に「{VERIFY_MARK}」と付ける。
- 上のルールのために、JSONの外に文章を足したり、指定されたキー以外を増やしたりしない。"""

GROUNDING_RULES_CHAT = f"""

## 根拠と出典のルール(必ず守る)
- 存在を確認できない判例・文献・条文番号・統計・人名は挙げない。必要なら具体名を書かず「{CHECK_MARK}」とだけ書く。
- 確信が持てない内容や、推測を含む内容は、その文末に「{VERIFY_MARK}」と付け、事実と推測を区別する。
- ユーザーが資料を提示している場合は、その資料にある内容だけを根拠にし、資料名と該当箇所を括弧で示す。"""
